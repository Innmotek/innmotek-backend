async function runMigration() {
  console.log('================================================================');
  console.log('STARTING SUPABASE POSTGRESQL SCHEMA & DATA MIGRATION');
  console.log('================================================================\n');

  const client = new Client({
    connectionString: process.env.SUPABASE_DB_URL,
    ssl: { rejectUnauthorized: false }
  });

  await client.connect();
  console.log('[1/4] Connected to Supabase PostgreSQL.\n');

  // Step A: Drop old public tables if re-running and create fresh schemas
  console.log('[2/4] Creating PostgreSQL Tables & Schemas...');
  for (const table of TABLE_MIGRATION_ORDER) {
    await client.query(`DROP TABLE IF EXISTS ${table} CASCADE;`);
    await client.query(TABLE_SCHEMAS[table]);
    console.log(`  ✓ Table '${table}' schema created.`);
  }

  // Step B: Ingest data table by table
  console.log('\n[3/4] Ingesting Data from Original SQL Dump into Supabase...');
  const rowCountSummary = [];

  for (const table of TABLE_MIGRATION_ORDER) {
    let rows = db.table(table).all();
    const originalCount = rows.length;

    // Apply the ONE approved deletion: Exclude Banner #25 ("Hello New")
    if (table === 'banners') {
      const beforeFilter = rows.length;
      rows = rows.filter(b => b.id !== 25 && b.title !== 'Hello New');
      console.log(`  - Banners table: Excluded Banner #25 ("Hello New"). Count ${beforeFilter} -> ${rows.length}`);
    }

    if (rows.length > 0) {
      const columns = Object.keys(rows[0]);
      const colList = columns.map(c => `"${c}"`).join(', ');

      for (const row of rows) {
        const values = columns.map(col => {
          let val = row[col];
          if (val === undefined || val === null || val === 'NULL') return null;
          return val;
        });

        const placeholders = values.map((_, idx) => `$${idx + 1}`).join(', ');
        const insertQuery = `INSERT INTO ${table} (${colList}) VALUES (${placeholders});`;
        await client.query(insertQuery, values);
      }

      // If table has an identity sequence, setval to MAX(id)
      const hasId = columns.includes('id');
      if (hasId) {
        await client.query(`
          SELECT setval(
            pg_get_serial_sequence('${table}', 'id'),
            COALESCE((SELECT MAX(id) FROM ${table}), 1),
            true
          );
        `);
      }
    }

    // Verify row count directly in Supabase
    const dbCountRes = await client.query(`SELECT COUNT(*)::int AS count FROM ${table};`);
    const supabaseCount = dbCountRes.rows[0].count;

    rowCountSummary.push({
      table,
      originalCount,
      supabaseCount,
      expectedCount: table === 'banners' ? originalCount - 1 : originalCount,
      match: supabaseCount === (table === 'banners' ? originalCount - 1 : originalCount)
    });
    console.log(`  ✓ Migrated '${table}': Original=${originalCount} | Supabase=${supabaseCount}`);
  }

  // Step C: Execute Spot Checks
  console.log('\n[4/4] Executing Post-Migration Spot Checks...');

  // Spot Check 1: HELIX product (id 15)
  console.log('\n--- SPOT CHECK 1: HELIX Product (ID 15) in Supabase ---');
  const helixRes = await client.query(`SELECT id, title, slug, specification, installation, warrenty FROM products WHERE id = 15;`);
  console.log('Query: SELECT id, title, slug, specification, installation, warrenty FROM products WHERE id = 15;');
  console.log('Result:');
  console.log(JSON.stringify(helixRes.rows[0], null, 2));

  // Spot Check 2: Admin user & permissions
  console.log('\n--- SPOT CHECK 2: Admin User & Role in Supabase ---');
  const adminRes = await client.query(`
    SELECT u.id, u.name, u.email, r.name AS role_name, COUNT(p.id) AS permissions_count
    FROM users u
    LEFT JOIN model_has_roles mhr ON u.id = mhr.model_id AND mhr.model_type = 'App\\Models\\User'
    LEFT JOIN roles r ON mhr.role_id = r.id
    LEFT JOIN role_has_permissions rhp ON r.id = rhp.role_id
    LEFT JOIN permissions p ON rhp.permission_id = p.id
    WHERE u.email = 'admin@innmotek.com'
    GROUP BY u.id, u.name, u.email, r.name;
  `);
  console.log('Query: Joined users + model_has_roles + roles + permissions for admin@innmotek.com');
  console.log('Result:');
  console.log(JSON.stringify(adminRes.rows[0], null, 2));

  // Spot Check 3: Confirm Banner #25 is deleted
  console.log('\n--- SPOT CHECK 3: Confirm Banner #25 Absent in Supabase ---');
  const banner25Res = await client.query(`SELECT * FROM banners WHERE id = 25;`);
  console.log('Query: SELECT * FROM banners WHERE id = 25;');
  console.log(`Result rows count: ${banner25Res.rows.length} (Expected: 0)`);

  await client.end();

  return rowCountSummary;
}

runMigration().catch(console.error);
